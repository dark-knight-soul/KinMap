import { describe, expect, it } from 'vitest';
import { genderSurname } from './names';

describe('род фамилии', () => {
  it.each([
    ['Иванов', 'F', 'Иванова'],
    ['Каримов', 'F', 'Каримова'],
    ['Соловьёв', 'F', 'Соловьёва'],
    ['Пушкин', 'F', 'Пушкина'],
    ['Невский', 'F', 'Невская'],
    ['Трубецкой', 'F', 'Трубецкая'],
    ['Толстой', 'F', 'Толстая'],
    ['Иванова', 'M', 'Иванов'],
    ['Невская', 'M', 'Невский'],
    ['Иванова', 'F', 'Иванова'],
    ['Иванов', 'M', 'Иванов'],
    ['Шевченко', 'F', 'Шевченко'],
    ['Цой', 'F', 'Цой'],
    ['Smith', 'F', 'Smith'],
    ['Иванов', 'U', 'Иванов'],
    ['', 'F', ''],
  ] as const)('%s (%s) → %s', (s, sex, expected) => {
    expect(genderSurname(s, sex)).toBe(expected);
  });
});
